"""Validate actual xr-hyper external references after compiling all four volumes.

Run from repository root:
  python application/scripts/verify_probability_aux.py --directory books/pl
This is NOT a substitute for LaTeX compilation: all four .pdf/.aux/.log files
must already have been generated by pdflatex/latexmk.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

VOLUMES = ("i", "ii", "iii", "iv")
PREFIXES = {"I": "i", "II": "ii", "III": "iii", "IV": "iv"}
EXTERNAL = re.compile(r"\\externaldocument\[([IV]+)-\]\{probability_volume_([iv]+)\}")
INPUT = re.compile(r"\\input\{([^{}]+)\}")
CITATION = re.compile(r"\\(?:ref|eqref|pageref|autoref|nameref|cref|Cref|vref|Vref)\s*\{([^{}]+)\}")
LABEL = re.compile(r"\\newlabel\{([^{}]+)\}")
COMMENT = re.compile(r"(?<!\\)%[^\n]*")


def verify(folder: Path) -> dict:
    folder = folder.resolve()
    collected: dict[str, set[str]] = {}
    docs: dict[str, str] = {}
    imports: dict[str, dict[str, str]] = {}
    for vol in VOLUMES:
        stem = f"probability_volume_{vol}"
        main = folder / f"{stem}.tex"
        pdf, aux, log = (folder / f"{stem}.{x}" for x in ("pdf", "aux", "log"))
        for filename in (main, pdf, aux, log):
            if not filename.is_file() or filename.stat().st_size == 0:
                raise ValueError(f"Missing or empty file: {filename}")
        body = main.read_text(encoding="utf-8-sig")
        docs[vol] = body
        imported = {}
        for prefix, target in EXTERNAL.findall(COMMENT.sub("", body)):
            if target != PREFIXES.get(prefix) or target == vol:
                raise ValueError(f"Bad external import {prefix} / {target} in {stem}")
            imported[prefix] = target
        imports[vol] = imported
        aux_body = aux.read_text(encoding="utf-8", errors="replace")
        collected[vol] = set(LABEL.findall(aux_body))
        if not collected[vol]:
            raise ValueError(f"No original labels in {aux}")
    external_counts = {}
    failures = []
    for vol in VOLUMES:
        body = docs[vol]
        sources = [body]
        for name in INPUT.findall(COMMENT.sub("", body)):
            target = (folder / name).resolve()
            if not target.is_relative_to(folder.parents[1]):
                raise ValueError(f"Unsafe input path: {name}")
            if not target.is_file():
                raise ValueError(f"Input missing: {target}")
            sources.append(target.read_text(encoding="utf-8-sig"))
        refs = 0
        for source in sources:
            for raw in CITATION.findall(COMMENT.sub("", source)):
                for target in raw.split(","):
                    label = target.strip()
                    m = re.match(r"^(I|II|III|IV)-(.+)$", label)
                    if not m:
                        continue
                    prefix, name = m.groups()
                    refs += 1
                    destination = imports[vol].get(prefix)
                    if destination is None or name not in collected[destination]:
                        failures.append(f"{vol}: {label} -> {destination or 'no import'} (not in AUX)")
        external_counts[vol] = refs
        log_text = (folder / f"probability_volume_{vol}.log").read_text(
            encoding="utf-8", errors="replace"
        )
        for line in log_text.splitlines():
            if "LaTeX Warning: Reference" in line and "undefined" in line:
                failures.append(f"{vol}: {line}")
    report = {
        "documents": 4, "native_aux_labels": {x: len(collected[x]) for x in VOLUMES},
        "checked_prefixed_references": external_counts,
        "sum_checked": sum(external_counts.values()), "failures": failures,
        "passed": not failures and sum(external_counts.values()) > 0,
    }
    (folder / "probability_xr_verification.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--directory", type=Path, required=True)
    args = parser.parse_args()
    try:
        report = verify(args.directory)
    except (OSError, ValueError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(2)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    raise SystemExit(0 if report["passed"] else 2)
