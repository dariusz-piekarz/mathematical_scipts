"""Independent skeptical finite checks for measure-theory chapter 03.

Enumerates arbitrary nonnegative covering costs and checks the induced
outer measure; separately tests the gap between Caratheodory sets and
the completion without sigma-finiteness. These are regression checks,
not substitutes for the general mathematical proofs.
"""
from itertools import product
from math import inf

COSTS = (0, 1, 2, inf)


def outer_by_cover(cost):
    # Exact optimal finite covering unions. Every countable cover of
    # a three-element set contains a subcover with at most three sets.
    dp = [inf] * 8
    dp[0] = 0
    for old in range(8):
        for a in range(1, 8):
            new = old | a
            if new != old:
                dp[new] = min(dp[new], dp[old] + cost[a])
    return tuple(min(dp[sup] for sup in range(8) if e & sup == e)
                 for e in range(8))


def caratheodory_family(outer):
    return {
        e for e in range(8)
        if all(outer[t] == outer[t & e] + outer[t & (7 ^ e)]
               for t in range(8))
    }


def exhaustive_cover_costs():
    checked = 0
    measurable_total = 0
    agreements = 0
    nonadditive_agreements = 0
    without_agreement = 0
    for val in product(COSTS, repeat=7):
        cost = (0, *val)
        outer = outer_by_cover(cost)
        assert outer[0] == 0
        for a in range(8):
            assert outer[a] <= cost[a]
            for b in range(8):
                if a & b == a:
                    assert outer[a] <= outer[b]
                assert outer[a | b] <= outer[a] + outer[b]
        measurable = caratheodory_family(outer)
        assert 0 in measurable and 7 in measurable
        assert all((7 ^ e) in measurable for e in measurable)
        assert all((a | b) in measurable
                   for a in measurable for b in measurable)
        assert all(outer[a | b] == outer[a] + outer[b]
                   for a in measurable for b in measurable if not (a & b))
        checked += 1
        measurable_total += len(measurable)
        if outer == cost:
            agreements += 1
            if any(cost[a | b] != cost[a] + cost[b]
                   for a in range(8) for b in range(8) if not (a & b)):
                nonadditive_agreements += 1
        else:
            without_agreement += 1
    assert checked == 4**7 == 16384
    assert agreements == 81 and nonadditive_agreements == 43
    print(
        f"PASS arbitrary cover costs: {checked} systems, "
        f"{measurable_total} measurable-set instances, "
        f"{agreements} preserve costs (including "
        f"{nonadditive_agreements} nonadditive), "
        f"{without_agreement} lower some cost"
    )


def non_sigma_finite_completion_gap():
    # Algebra generated by {0,1} and {2,3}: the first atom has
    # infinite premeasure, the other atom has mass 1.
    A, B, X = 0b0011, 0b1100, 0b1111
    algebra = (0, A, B, X)
    pre = {0: 0, A: inf, B: 1, X: inf}
    assert pre[A | B] == pre[A] + pre[B]
    assert all((e & A) == 0 for e in algebra if pre[e] < inf)
    outer = {
        e: min(pre[c] for c in algebra if e & c == e)
        for e in range(16)
    }
    measurable = {
        e for e in range(16)
        if all(outer[t] == outer[t & e] + outer[t & (X ^ e)]
               for t in range(16))
    }
    completed = {
        e for e in range(16)
        if any(a & e == a and e & b == e
               and pre[b & (X ^ a)] == 0
               for a in algebra for b in algebra if a & b == a)
    }
    assert len(measurable) == 8 and completed == set(algebra)
    assert 0b0001 in measurable and 0b0001 not in completed
    assert set(algebra).issubset(measurable)
    print(
        f"PASS non-sigma-finite: Caratheodory {len(measurable)} sets, "
        f"completion {len(completed)} sets"
    )


if __name__ == "__main__":
    exhaustive_cover_costs()
    non_sigma_finite_completion_gap()
