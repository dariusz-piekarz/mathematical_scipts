#!/usr/bin/env python3
"""Independent finite-model test of topological convergence, Chapter 06.

Finite spaces test closure, sequential closure, proper filters,
Hausdorff uniqueness and continuity via filters without assuming T1.
"""
from itertools import product
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
CHAPTER = ROOT / 'chapters/pl/general_topology/06-zbieznosc-topologiczna.tex'
BOOK = ROOT / 'books/pl/general_topology.tex'


def all_subsets(n):
    return tuple(range(1 << n))


def topologies(n):
    full = (1 << n) - 1
    subsets = all_subsets(n)
    for membership in range(1 << (1 << n)):
        tau = frozenset(u for u in subsets if membership & (1 << u))
        if 0 not in tau or full not in tau:
            continue
        if all((u | v) in tau and (u & v) in tau for u in tau for v in tau):
            yield tau


def closure(n, tau, a):
    full = (1 << n) - 1
    result = full
    for u in tau:
        closed = full ^ u
        if (a & ~closed) == 0:
            result &= closed
    return result


def nhds(n, tau, x):
    return tuple(u for u in tau if u & (1 << x))


def filter_limit(n, tau, basis, x):
    # On a finite set, the proper filter generated by nonempty basis
    # B consists of all sets that contain B.
    return all((u & basis) == basis for u in nhds(n, tau, x))


def image_set(mapping, a):
    return sum(1 << mapping[j] for j in range(len(mapping)) if a & (1 << j)
               and not any((a & (1 << k)) and mapping[k] == mapping[j] for k in range(j)))


def continuous(n, m, tau, sigma, mapping):
    for v in sigma:
        pre = sum(1 << j for j in range(n) if v & (1 << mapping[j]))
        if pre not in tau:
            return False
    return True


counts = (1, 1, 4, 29, 355)
all_topologies = {}
filter_cases = 0
for n in range(5):
    full = (1 << n) - 1
    ts = tuple(topologies(n))
    assert len(ts) == counts[n], (n, len(ts))
    all_topologies[n] = ts
    for tau in ts:
        is_t2 = all(any(u & (1 << x) and v & (1 << y) and not (u & v)
                        for u in tau for v in tau)
                    for x in range(n) for y in range(n) if x != y)
        # A finite proper filter is principal on a nonempty subset.
        # It converges iff every open neighbourhood contains the generator.
        limits_by_b = {}
        for b in range(1, full + 1):
            limits_by_b[b] = {x for x in range(n) if filter_limit(n,tau,b,x)}
            filter_cases += n
        assert is_t2 == all(len(s) <= 1 for s in limits_by_b.values())
        for a in range(full + 1):
            cl = closure(n,tau,a)
            for x in range(n):
                in_closure = bool(cl & (1 << x))
                has_filter = any((b & a) == b and x in limits_by_b[b]
                                 for b in range(1, full + 1))
                assert in_closure == has_filter, (n,tau,a,x)
                # Every finite topology is first-countable: constant nets
                # and constant sequences detect closure.
                has_seq = any((a & (1 << y)) and
                              all(u & (1 << y) for u in nhds(n,tau,x))
                              for y in range(n))
                assert in_closure == has_seq
    print(f'PASS finite topologies n={n}: {len(ts)}')

map_checks = 0
for n in range(4):
    for m in range(4):
        for tau in all_topologies[n]:
            for sigma in all_topologies[m]:
                for mapping in product(range(m),repeat=n):
                    con = continuous(n,m,tau,sigma,mapping)
                    preserv = all(
                        not filter_limit(n,tau,b,x) or
                        filter_limit(m,sigma,image_set(mapping,b),mapping[x])
                        for b in range(1,1 << n) for x in range(n)
                    )
                    assert con == preserv,(n,m,tau,sigma,mapping)
                    map_checks += 1

# Audit 02: generalized sequences (nets) indexed by arbitrary finite directed
# preorders, including nonantisymmetric preorders and nonlinear directions.
net_checks = 0
nonlinear_preorders = 0
for dn in range(1, 4):
    for matrix in range(1 << (dn * dn)):
        le = lambda i, j: bool(matrix & (1 << (i * dn + j)))
        if not all(le(i, i) for i in range(dn)):
            continue
        if not all(not (le(i, j) and le(j, k)) or le(i, k)
                   for i in range(dn) for j in range(dn) for k in range(dn)):
            continue
        if not all(any(le(i, k) and le(j, k) for k in range(dn))
                   for i in range(dn) for j in range(dn)):
            continue
        if any(not le(i, j) and not le(j, i) for i in range(dn) for j in range(dn)):
            nonlinear_preorders += 1
        for xn in range(1, 4):
            for tau in all_topologies[xn]:
                for values in product(range(xn), repeat=dn):
                    tails = tuple(frozenset(values[j] for j in range(dn)
                                            if le(i, j)) for i in range(dn))
                    assert all(tails[i] for i in range(dn))
                    # Tail-images form a filter base; this is the crucial use
                    # of the directed-preorder axiom.
                    assert all(any(tails[k] <= (tails[i] & tails[j])
                                   for k in range(dn))
                               for i in range(dn) for j in range(dn))
                    for x in range(xn):
                        nbhds = nhds(xn, tau, x)
                        via_net = all(any(all((u & (1 << values[j])) != 0
                                                  for j in range(dn) if le(i, j))
                                              for i in range(dn))
                                      for u in nbhds)
                        via_tails = all(any(all(u & (1 << y) for y in tail)
                                                for tail in tails)
                                        for u in nbhds)
                        assert via_net == via_tails
                        net_checks += 1
assert nonlinear_preorders > 0
print(f'PASS generalized sequences: {net_checks} directed-preorder/topology/limit cases; '
      f'{nonlinear_preorders} nonlinear directed preorders')

# Audit 03: finite shadow of the explicit co-countable-topology net.
# On an uncountable A every countable C has a point outside C;
# finite models here check the pair indexing, direction and avoidance
# of prescribed exceptional sets, not the uncountability argument.
net_exceptions_checks = 0
for finite_domain_size in range(4, 8):
    # Allow every exceptional subset of a tracked 3-point portion of A.
    A = frozenset(range(finite_domain_size))
    tracked = frozenset(range(3))
    exceptional = tuple(frozenset(i for i in tracked if mask & (1 << i))
                        for mask in range(1 << len(tracked)))
    D = tuple((C,a) for C in exceptional for a in sorted(A-C))
    assert D and {a for C,a in D} == A
    for C,a in D:
        for E,b in D:
            # The upper index (C union E, c) is valid and exists.
            B = C | E
            assert B in exceptional
            assert any((B,c) in D for c in A-B)
            net_exceptions_checks += 1
    for C in exceptional:
        d0 = next(d for d in D if d[0] == C)
        assert all(a not in C for E,a in D if d0[0] <= E)
        net_exceptions_checks += 1
print(f'PASS explicit generalized net finite-index regression: {net_exceptions_checks} checks')

# Audit 04: images of members of any proper filter form a filter base.
# For finite sets every proper filter is determined by a nonempty core B.
image_basis_checks = 0
for n in range(1, 5):
    for m in range(1, 4):
        for mapping in product(range(m), repeat=n):
            for core in range(1, 1 << n):
                filt = tuple(F for F in range(1 << n) if (F & core) == core)
                assert filt
                images = tuple(image_set(mapping, F) for F in filt)
                assert all(images)
                for F in filt:
                    for G in filt:
                        H = F & G
                        assert H in filt
                        assert (image_set(mapping, H) & ~(image_set(mapping, F) & image_set(mapping, G))) == 0
                        image_basis_checks += 1
print(f'PASS image-filter bases: {image_basis_checks} finite-model checks')

