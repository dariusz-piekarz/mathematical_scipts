#!/usr/bin/env python3
"""Cross-script dependency audit and finite uniform-completion sanity models.

Source checks verify that chapters 23--26 do not cite theorems introduced
later. Finite filters test the logical content of chapter 13's construction;
none of these checks replaces a mathematical proof.
"""
from __future__ import annotations

from itertools import combinations, product
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[2]


def source_dependencies() -> tuple[int, int]:
    catalog = json.loads((ROOT / "catalog/books.json").read_text(encoding="utf-8"))
    chapters = next(x["chapters"] for x in catalog["books"]
                    if x["id"] == "general_topology")
    assert len(chapters) >= 26
    owner: dict[str, int] = {}
    contents = []
    for i, path in enumerate(chapters, 1):
        source = (ROOT / path).read_text(encoding="utf-8")
        contents.append(source)
        for label in re.findall(r"\\label\{([^}]+)\}", source):
            assert label not in owner, label
            owner[label] = i

    edges = []
    for i, source in enumerate(contents, 1):
        for label in re.findall(r"\\(?:ref|eqref|pageref|autoref)\{([^}]+)\}", source):
            assert label in owner, (i, label)
            if i >= 23:
                assert owner[label] <= i, (
                    "newer topology chapter depends on a future chapter",
                    i, label, owner[label])
            if owner[label] != i:
                edges.append((i, owner[label], label))

    assert (25, 23, "ex:topog23-cantor") in edges
    assert (26, 25, "thm:topog25-space-filling") in edges
    assert (26, 10, "thm:topog-urysohn-metryzowalnosc") in edges
    assert (26, 8, "thm:topog-spojnosc-lokalna-komponenty") in edges

    # Brouwer's theorem is an explicit (non-circular) external dependency.
    topo_alg = (ROOT / "chapters/pl/algebraic_topology/"
                "19-stopien-indeks-punktu-stalego-i-twierdzenie-lefschetza.tex")
    text = topo_alg.read_text(encoding="utf-8")
    assert r"\begin{wniosek}[Twierdzenie Brouwera]" in text
    assert "thm:lefschetz-v10" in text
    assert "twierdzenia Brouwera o punkcie stałym" in contents[22]
    return len(edges), len(owner)


def partitions(n: int):
    """Generate all partitions using canonical restricted-growth strings."""
    def rec(values: tuple[int, ...], m: int):
        if len(values) == n:
            yield values
        else:
            for k in range(m + 2):
                yield from rec(values + (k,), max(m, k))
    if n:
        yield from rec((0,), 0)


def finite_cauchy_minimal_models() -> tuple[int, int]:
    """Finite uniformity generated by a partition equivalence relation R.

    Principal filter F_A={S: A subseteq S}. It is Cauchy iff all points
    in A lie in one R-class. The minimal Cauchy filter close to F_A is
    F_[a], generated by the full R-class. Check this on n <= 5.
    """
    model_count = 0
    closeness_checks = 0
    for n in range(1, 6):
        universe = frozenset(range(n))
        for code in partitions(n):
            classes = {
                frozenset(x for x in range(n) if code[x] == k)
                for k in set(code)
            }
            cauchy = [
                frozenset(S) for k in range(1, n + 1)
                for S in combinations(range(n), k)
                if any(set(S) <= C for C in classes)
            ]
            for A in cauchy:
                cls = next(C for C in classes if A <= C)
                # For the least entourage R, R[A] is the whole class.
                RA = frozenset(x for x in universe
                               if any(code[x] == code[a] for a in A))
                assert RA == cls
                assert A <= RA
                # Principal-filter inclusion F_RA <= F_A, and F_RA
                # is the smallest Cauchy filter in this equivalence class.
                for B in cauchy:
                    close = all(code[a] == code[b] for a in A for b in B)
                    if close:
                        assert B <= cls
                        assert RA >= B
                    else:
                        assert any(code[a] != code[b] for a in A for b in B)
                    closeness_checks += 1
                model_count += 1
    return model_count, closeness_checks


if __name__ == "__main__":
    edges, labels = source_dependencies()
    models, checks = finite_cauchy_minimal_models()
    print(f"PASS topology dependencies: {edges} cross-chapter references, "
          f"{labels} labels, {models} finite Cauchy filters, "
          f"{checks} filter-closeness checks")
