def partitions(n: int):
    """Generate each set partition once, as a restricted-growth string."""
    if n == 0:
        yield ()
        return

    def visit(prefix: tuple[int, ...], greatest: int):
        if len(prefix) == n:
            yield prefix
            return
        for nxt in range(greatest + 2):
            yield from visit(prefix + (nxt,), max(greatest, nxt))

    yield from visit((0,), 0)


def finite_partition_checks():
    # Finite uniformities are generated by equivalence relations. Every
    # proper filter on a finite space is the principal filter of a
    # nonempty A. It is Cauchy exactly when A lies in one equivalence
    # class; two Cauchy filters are close iff those classes coincide.
    # The minimal filters are exactly the principal filters of blocks.
    bell_numbers = (1, 1, 2, 5, 15)
    total, filters_checked = 0, 0
    for n in range(5):
        cases = 0
        for labels in partitions(n):
            cases += 1
            total += 1
            if n == 0:
                # There is one uniformity, but no proper filter.
                continue
            blocks = [frozenset(i for i, k in enumerate(labels) if k == j)
                      for j in range(max(labels) + 1)]
            equiv = {(i, j) for B in blocks for i in B for j in B}
            cauchy = []
            for mask in range(1, 1 << n):
                A = frozenset(i for i in range(n) if mask & (1 << i))
                is_cauchy = all((i, j) in equiv for i in A for j in A)
                if not is_cauchy:
                    continue
                cauchy.append(A)
                filters_checked += 1
                class_of_A = next(B for B in blocks if A <= B)
                # F_A^° is generated by E[A], whose minimum as E runs
                # through the uniformity is the equivalence class of A.
                enlarged = frozenset(j for j in range(n)
                                      if any((i, j) in equiv for i in A))
                assert enlarged == class_of_A
                assert any(all((i, j) in equiv for j in A) for i in range(n))

            # A principal Cauchy filter on A is minimal precisely if
            # its generator is a full equivalence class.
            minimal_generators = {A for A in cauchy
                                  if not any(A < B for B in cauchy)}
            assert minimal_generators == set(blocks)
            assert len(minimal_generators) == len(blocks)

            for A in cauchy:
                for B in cauchy:
                    close = all((i, j) in equiv for i in A for j in B)
                    same_minimal = (
                        next(C for C in blocks if A <= C)
                        == next(C for C in blocks if B <= C))
                    assert close == same_minimal
        assert cases == bell_numbers[n], (n, cases)
    assert total == sum(bell_numbers)
    assert filters_checked > 0
    return total, filters_checked



def finite_entourage_orientation_checks():
    """Regression: the image of an entourage need not be symmetric.

    Finite uniformities have a least entourage R, an equivalence
    relation, but their larger entourages may be asymmetric. In the
    completion, one must use a symmetric D subset E when reversing
    the direction of an entourage at a dense point.
    """
    n = 3
    all_pairs = {(i, j) for i in range(n) for j in range(n)}
    checked = 0
    asymmetric = 0
    for labels in partitions(n):
        blocks = [frozenset(i for i, k in enumerate(labels) if k == j)
                  for j in range(max(labels) + 1)]
        R = {(i, j) for block in blocks for i in block for j in block}
        other_pairs = sorted(all_pairs - R)
        for mask in range(1 << len(other_pairs)):
            E = R | {pair for k, pair in enumerate(other_pairs)
                     if mask & (1 << k)}
            D = E & {(b, a) for a, b in E}
            assert R <= D <= E
            assert D == {(b, a) for a, b in D}
            # Every minimal Cauchy filter is the principal filter
            # of its R-class. Choosing x in the class witnesses
            # both directions in the symmetric entourage D.
            for block in blocks:
                for x in block:
                    assert all((a, x) in D and (x, a) in D
                               for a in block)
            if any((b, a) not in E for a, b in E):
                asymmetric += 1
            checked += 1
    assert asymmetric > 0, "asymmetric entourages must be exercised"
    return checked, asymmetric

def lint():
    source = (ROOT / CH).read_text(encoding="utf-8")
    assert (ROOT / STANDALONE).is_file()
    assert r"\input{../../" + CH + "}" in (ROOT / BOOK).read_text(encoding="utf-8")
    assert r"\input{../../" + CH + "}" in (ROOT / STANDALONE).read_text(encoding="utf-8")
    entry = next(b for b in json.loads((ROOT / "catalog/books.json").read_text())["books"]
                 if b["id"] == "general_topology")
    assert entry["chapters"][12] == CH
    labels, refs = [], []
    for p in entry["chapters"]:
        text = (ROOT / p).read_text(encoding="utf-8")
        labels.extend(re.findall(r"\\label\{([^}]+)\}", text))
        refs.extend(re.findall(r"\\(?:ref|eqref|pageref)\{([^}]+)\}", text))
        assert not re.search(r"zwartościowani\w*|zbieżności\s+zwartej", text, re.I)
    assert len(labels) == len(set(labels)), "duplicate labels"
    assert set(refs) <= set(labels), f"missing labels: {set(refs)-set(labels)}"
    for env in ("twierdzenie","lemat","stwierdzenie","wniosek","definicja",
                "przyklad","uwaga","proof"):
        assert source.count(r"\begin{" + env + "}") == source.count(
            r"\end{" + env + "}"), env
    assert r"\label{thm:topog-uzupelnienia-istnienie}" in source
    assert r"\label{thm:topog-uzupelnienia-uniwersalnosc}" in source
    example_start = source.index(r"\label{ex:topog-uzupelnienia-arctan}")
    example_end = source.index(r"\end{przyklad}", example_start)
    assert "samą topologię (rozdział~10)." in source[example_start:example_end], (
        "arctan metric example must refer to the chapter proving equivalence"
    )
    return len(labels),len(refs)

if __name__ == "__main__":
    n,filters=finite_partition_checks()
    checked, asymmetric = finite_entourage_orientation_checks()
    l,r=lint()
    print(f"PASS chapter 13 finite uniformities={n}, principal Cauchy filters={filters}, "
          f"entourage models={checked}, asymmetric={asymmetric}, labels={l}, refs={r}")
